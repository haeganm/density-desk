"""Nightly catalyst sweep: drive ChatGPT in real Chrome, write state/catalysts.json.

Setup (once):   .venv\\Scripts\\python.exe ops\\gpt_sweep.py --login   -> log into chatgpt.com
Nightly:        scheduled task DensityDesk-GptSweep (21:30), or run with no args.
Self-test:      ops\\gpt_sweep.py --selftest   (parser only, no browser)

Failure is a safe no-op: catalysts.json untouched, catalyst_sweep_fail logged,
desk just runs with normal thresholds. Manual paste remains the fallback."""
import json
import os
import sys
import time
sys.path.insert(0, r"C:\density desk")
import config
import db

if sys.stdout is None or sys.stderr is None:   # pythonw scheduled task: self-log
    (config.ROOT / "state").mkdir(exist_ok=True)
    _log = open(config.ROOT / "state" / "gpt_sweep.log", "a", buffering=1,
                encoding="utf-8")
    sys.stdout = sys.stdout or _log
    sys.stderr = sys.stderr or _log

PROFILE = config.ROOT / "state" / "chrome-profile"
PROMPT_MD = config.ROOT / "docs" / "gpt-catalyst-prompt.md"
OUT = config.ROOT / "state" / "catalysts.json"
HORIZON_S = 72 * 3600


def prompt_text() -> str:
    md = PROMPT_MD.read_text(encoding="utf-8")
    return md.split("---", 1)[-1].strip()      # everything below the FIRST --- rule


def _extract_json(reply: str) -> dict:
    """Last valid JSON object containing 'windows'. A greedy brace regex breaks on
    any prose brace, so walk '{' positions with a real decoder instead."""
    dec = json.JSONDecoder()
    found = None
    for i, ch in enumerate(reply):
        if ch == "{":
            try:
                obj, _ = dec.raw_decode(reply, i)
            except ValueError:
                continue
            if isinstance(obj, dict) and "windows" in obj:
                found = obj
    if found is None:
        raise ValueError("no JSON object with 'windows' in reply")
    return found


def parse_windows(reply: str, now: float | None = None) -> list[dict]:
    """Extract + validate. Raises ValueError if unusable — caller must NOT
    overwrite a good catalysts.json on failure."""
    now = now or time.time()
    data = _extract_json(reply)
    wins = []
    for w in data.get("windows", []):
        try:
            s, e, f = float(w["start_ts"]), float(w["end_ts"]), float(w.get("factor", 2.0))
        except (KeyError, TypeError, ValueError):
            continue
        if s > 1e11:                            # GPT sometimes emits milliseconds
            s, e = s / 1000, e / 1000
        if s < e and now - 3600 <= e and s <= now + HORIZON_S and 1.0 <= f <= 99.0:
            wins.append({"label": str(w.get("label", "?"))[:80],
                         "start_ts": s, "end_ts": e, "factor": f})
    if data.get("windows") and not wins:
        raise ValueError("all windows failed validation — keeping previous file")
    return wins


def write_catalysts(wins: list[dict]) -> None:
    payload = {"_doc": "auto-generated by ops/gpt_sweep.py; windows widen edge "
                       "thresholds by `factor`", "generated_ts": time.time(),
               "windows": wins}
    tmp = OUT.with_suffix(".tmp")
    tmp.write_text(json.dumps(payload, indent=1), encoding="utf-8")
    os.replace(tmp, OUT)


CHROME = r"C:\Program Files\Google\Chrome\Application\chrome.exe"


def do_login():
    """Seed the profile with PLAIN Chrome (no automation): Google SSO blocks
    OAuth in CDP-controlled browsers, but a session created in vanilla Chrome
    is reused fine by the nightly Playwright run."""
    import subprocess
    print("Chrome opening: sign into chatgpt.com (Google button works here), "
          "then close ALL windows of that Chrome instance.")
    subprocess.run([CHROME, f"--user-data-dir={PROFILE}", "--no-first-run",
                    "--no-default-browser-check", "https://chatgpt.com/"])
    print("Profile saved. Test with: ops\\gpt_sweep.py (no args)")


def run_browser() -> str:
    from playwright.sync_api import sync_playwright

    with sync_playwright() as pw:
        ctx = pw.chromium.launch_persistent_context(
            str(PROFILE), channel="chrome", headless=False,
            args=["--window-position=-32000,-32000"],
            viewport={"width": 1280, "height": 900})
        page = ctx.pages[0] if ctx.pages else ctx.new_page()
        page.goto("https://chatgpt.com/", wait_until="domcontentloaded", timeout=60_000)
        composer = page.locator("#prompt-textarea, div[contenteditable='true']").first
        composer.wait_for(state="visible", timeout=45_000)
        composer.click()
        composer.fill(prompt_text())
        page.keyboard.press("Enter")
        # streaming done when the stop button goes away (bounded)
        stop = page.locator("button[data-testid='stop-button']")
        try:
            stop.wait_for(state="visible", timeout=20_000)
        except Exception:
            pass                                    # short replies can finish instantly
        stop.wait_for(state="hidden", timeout=420_000)   # out-of-quota fallback models answer slowly
        page.wait_for_timeout(1_500)
        reply = page.locator("div[data-message-author-role='assistant']").last.inner_text()
        ctx.close()
        return reply


def selftest():
    now = time.time()
    win = '{"windows": [{"label": "CPI", "start_ts": %d, "end_ts": %d, "factor": 2}]}' \
          % (now + 3600, now + 7200)
    assert len(parse_windows(win)) == 1
    # prose braces around the JSON (ChatGPT's normal style) must not break extraction
    prosey = "I considered {FOMC, CPI} events:\n" + win + "\nnote: {factor} widens"
    assert len(parse_windows(prosey)) == 1
    # millisecond timestamps normalized, not dropped
    ms = '{"windows": [{"label": "CPI", "start_ts": %d, "end_ts": %d, "factor": 2}]}' \
         % ((now + 3600) * 1000, (now + 7200) * 1000)
    assert len(parse_windows(ms)) == 1
    assert parse_windows('{"windows": []}') == []
    for bad, why in [("no json here", "junk"),
                     ('{"windows": [{"label": "old", "start_ts": 1, "end_ts": 2, '
                      '"factor": 2}]}', "all-invalid must raise, not write empty")]:
        try:
            parse_windows(bad)
            raise AssertionError(why)
        except ValueError:
            pass
    print("PASS selftest")


def main():
    if "--selftest" in sys.argv:
        return selftest()
    if "--login" in sys.argv:
        return do_login()
    con = None
    try:
        con = db.connect()
        reply = run_browser()
        wins = parse_windows(reply)
        write_catalysts(wins)
        db.log_event(con, "catalyst_sweep", f"{len(wins)} windows: "
                     + ", ".join(w["label"] for w in wins[:6]))
        print(f"OK {len(wins)} windows")
    except Exception as e:
        if con is not None:
            db.log_event(con, "catalyst_sweep_fail", str(e)[:300])
        print(f"FAIL {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
